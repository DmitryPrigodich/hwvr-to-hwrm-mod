end
function Gallery_Next()
    if Gallery_Mode~="pair" then Gallery_Show(Gallery_First[Gallery_CurrentGroup]); return end
    local index=Gallery_Current+1
    if index>Gallery_Total then index=1 end
    Gallery_Show(index)
end
function Gallery_Previous()
    if Gallery_Mode~="pair" then Gallery_Show(Gallery_Last[Gallery_CurrentGroup]); return end
    local index=Gallery_Current-1
    if index<1 then index=Gallery_Total end
    Gallery_Show(index)
end
function Gallery_NextGroup()
