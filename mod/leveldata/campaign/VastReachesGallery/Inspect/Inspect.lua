function Gallery_Show(index)
    Gallery_Current=index
    Gallery_CurrentGroup=Gallery_EntryGroups[index]
    Gallery_CurrentFaction=Gallery_GroupFactions[Gallery_CurrentGroup]
    Gallery_Mode="pair"
    Camera_Interpolate("here","Gallery_Camera"..index,0)
    Subtitle_Message("$"..(9904000+index),900)
    print("VR_GALLERY: view="..index)
end
function Gallery_Group(index)
    Gallery_CurrentGroup=index
    Gallery_CurrentFaction=Gallery_GroupFactions[index]
    Gallery_Current=Gallery_First[index]
    Gallery_Mode="group"
    Camera_Interpolate("here","Gallery_Group"..index,0)
    Subtitle_Message("$"..(9906000+index),900)
    print("VR_GALLERY: group="..index)
end
function Gallery_Category(index)
    local group=Gallery_FactionGroups[Gallery_CurrentFaction][index]
    if group~=nil then Gallery_Group(group) end
end
function Gallery_Faction(index)
